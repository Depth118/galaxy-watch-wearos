#!/usr/bin/env python3
"""Render printable ASCII in Noto Sans (SIL OFL) to an anti-aliased bitmap font
header for r800wdui.c:   mkfont.py > wdfont.h      (needs ImageMagick 7)

Two faces: 0 = body (Noto Sans 21 pt), 1 = title (Noto Sans Bold 28 pt).
Each glyph is an 8-bit alpha strip of the face's fixed line height.
"""
import subprocess
import sys

MAGICK = "magick"
FACES = [("Noto-Sans", 21), ("Noto-Sans-Bold", 28)]


def render(font, size, ch):
    if ch == " ":  # label: refuses a lone space: blank glyph of the advance width
        w2 = render(font, size, "x")[0]
        w3, h, _ = render(font, size, "x x")
        w = w3 - 2 * w2
        return w, h, bytes(w * h)
    # "label:" treats a leading '@' as a file name and '\' as an escape
    text = {"@": "\\@", "\\": "\\\\"}.get(ch, ch)
    args = [MAGICK, "-background", "black", "-fill", "white", "-font", font,
            "-pointsize", str(size), "label:" + text]
    dim = subprocess.run(args + ["-format", "%w %h", "info:"], capture_output=True,
                         text=True, check=True).stdout.split()
    w, h = int(dim[0]), int(dim[1])
    raw = subprocess.run(args + ["-depth", "8", "gray:-"], capture_output=True,
                         check=True).stdout
    assert len(raw) == w * h, (ch, w, h, len(raw))
    return w, h, raw


def main():
    out = ["/* generated by mkfont.py from Noto Sans (SIL Open Font License 1.1) */",
           "#include <stdint.h>"]
    for fi, (font, size) in enumerate(FACES):
        glyphs = [render(font, size, chr(c)) for c in range(32, 127)]
        h = glyphs[0][1]
        assert all(g[1] == h for g in glyphs), font
        offs, data = [], bytearray()
        for w, _, raw in glyphs:
            offs.append(len(data))
            data += raw
        out.append(f"#define F{fi}_H {h}")
        out.append(f"static const uint16_t f{fi}_w[95] = {{{','.join(str(g[0]) for g in glyphs)}}};")
        out.append(f"static const uint32_t f{fi}_off[95] = {{{','.join(map(str, offs))}}};")
        rows = [",".join(str(b) for b in data[i:i + 40]) for i in range(0, len(data), 40)]
        out.append(f"static const uint8_t f{fi}_px[{len(data)}] = {{\n" + ",\n".join(rows) + "};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
